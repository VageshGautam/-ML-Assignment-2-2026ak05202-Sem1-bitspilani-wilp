"""Interactive evaluation dashboard for five saved classification pipelines.

The app evaluates uploaded TEST data only; it never fits or retrains models.
Train the models first by running `python train_models.py`.
"""
from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns
import streamlit as st
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    matthews_corrcoef,
    precision_score,
    recall_score,
    roc_auc_score,
)

# ----------------------------------------------------------
# 1. APP CONFIGURATION AND SAVED MODEL LOCATIONS
# ----------------------------------------------------------
st.set_page_config(page_title="ML Classification Dashboard", layout="wide")

BASE_DIR = Path(__file__).resolve().parent
MODEL_DIR = BASE_DIR / "model"
TARGET_COLUMN = "diagnosis"
FEATURE_COLUMNS = [f"feature_{i}" for i in range(1, 31)]

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "KNN": "knn.joblib",
    "Naive Bayes": "naive_bayes.joblib",
    "SVM": "svm.joblib",
}

# ----------------------------------------------------------
# 2. PAGE HEADING AND CONTROLS
# ----------------------------------------------------------
st.title("Machine Learning Classification Dashboard")
st.write("Compare five pre-trained classifiers on a test CSV file.")
st.caption("Dataset: Breast Cancer Wisconsin (Diagnostic) | Target: diagnosis (0 = benign, 1 = malignant)")

with st.expander("Instructions: how to use this app"):
    st.write(
        "1. Run train_models.py once to create the five .joblib files. "
        "2. Upload the generated test_data.csv. "
        "3. Select a model. "
        "4. View its metrics, confusion matrix, and classification report, "
        "plus a side-by-side comparison of all five models."
    )

selected_model = st.selectbox("Select a classification model", list(MODEL_FILES))
uploaded_file = st.file_uploader("Upload the TEST dataset (CSV)", type=["csv"])

if uploaded_file is None:
    st.info("To begin, upload the test_data.csv created by train_models.py.")
    st.stop()

# ----------------------------------------------------------
# 3. READ AND VALIDATE THE UPLOADED TEST DATA
# ----------------------------------------------------------
try:
    test_df = pd.read_csv(uploaded_file)
except Exception as exc:
    st.error(f"The uploaded file could not be read as CSV: {exc}")
    st.stop()

if test_df.empty:
    st.error("The uploaded CSV is empty.")
    st.stop()

required_columns = FEATURE_COLUMNS + [TARGET_COLUMN]
missing_columns = [col for col in required_columns if col not in test_df.columns]
if missing_columns:
    st.error("Missing required columns: " + ", ".join(missing_columns))
    st.info("Please use the test_data.csv generated by train_models.py.")
    st.stop()

# Enforce the exact same input feature order as the training script.
X_test = test_df[FEATURE_COLUMNS].apply(pd.to_numeric, errors="coerce")
if X_test.isna().any().any():
    st.error("Some input feature values are missing or are not numeric.")
    st.stop()

# Accept both 0/1 labels and original B/M diagnosis labels.
target_values = test_df[TARGET_COLUMN].replace({"B": 0, "M": 1, "b": 0, "m": 1})
y_test = pd.to_numeric(target_values, errors="coerce")
if y_test.isna().any() or not y_test.isin([0, 1]).all():
    st.error("The diagnosis column must contain only 0/1 or B/M values.")
    st.stop()
y_test = y_test.astype(int)

st.success(f"Test dataset loaded successfully: {len(test_df)} rows and {len(FEATURE_COLUMNS)} input features.")
with st.expander("Preview uploaded test data"):
    st.dataframe(test_df.head(10))

# ----------------------------------------------------------
# 4. LOAD SAVED MODELS AND EVALUATE (NO RETRAINING)
# ----------------------------------------------------------
missing_models = [filename for filename in MODEL_FILES.values() if not (MODEL_DIR / filename).is_file()]
if missing_models:
    st.error("Saved model files are missing: " + ", ".join(missing_models))
    st.info("Run 'python train_models.py' first and check the model/ folder.")
    st.stop()

results = []
selected_predictions = None

try:
    for name, filename in MODEL_FILES.items():
        # Only load .joblib files created by you or another trusted source.
        model = joblib.load(MODEL_DIR / filename)
        predictions = model.predict(X_test)

        # AUC requires probability or decision scores, not predicted class labels.
        if hasattr(model, "predict_proba"):
            scores = model.predict_proba(X_test)[:, 1]
        else:
            scores = model.decision_function(X_test)

        # ROC-AUC is undefined if the test set has only one actual class.
        auc = roc_auc_score(y_test, scores) if y_test.nunique() == 2 else float("nan")

        results.append({
            "Model": name,
            "Accuracy": accuracy_score(y_test, predictions),
            "AUC": auc,
            "Precision": precision_score(y_test, predictions, zero_division=0),
            "Recall": recall_score(y_test, predictions, zero_division=0),
            "F1": f1_score(y_test, predictions, zero_division=0),
            "MCC": matthews_corrcoef(y_test, predictions),
        })
        if name == selected_model:
            selected_predictions = predictions
except Exception as exc:
    st.error(f"Unable to evaluate the saved models: {exc}")
    st.info("Check that the saved models were generated from this dataset and that your scikit-learn version is compatible.")
    st.stop()

# ----------------------------------------------------------
# 5. SHOW SIX METRICS FOR THE SELECTED MODEL
# ----------------------------------------------------------
selected_result = next(item for item in results if item["Model"] == selected_model)
st.subheader(f"Results: {selected_model}")

row1 = st.columns(3)
row1[0].metric("Accuracy", f"{selected_result['Accuracy']:.4f}")
row1[1].metric("AUC", f"{selected_result['AUC']:.4f}" if pd.notna(selected_result["AUC"]) else "N/A")
row1[2].metric("Precision", f"{selected_result['Precision']:.4f}")

row2 = st.columns(3)
row2[0].metric("Recall", f"{selected_result['Recall']:.4f}")
row2[1].metric("F1 Score", f"{selected_result['F1']:.4f}")
row2[2].metric("MCC Score", f"{selected_result['MCC']:.4f}")

if y_test.nunique() < 2:
    st.warning("AUC is unavailable because the uploaded test file contains only one target class.")

# ----------------------------------------------------------
# 6. CONFUSION MATRIX AND CLASSIFICATION REPORT
# ----------------------------------------------------------
st.subheader("Confusion Matrix")
cm = confusion_matrix(y_test, selected_predictions, labels=[0, 1])
fig, ax = plt.subplots(figsize=(6, 4))
sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=["Benign (0)", "Malignant (1)"],
    yticklabels=["Benign (0)", "Malignant (1)"],
    ax=ax,
)
ax.set_xlabel("Predicted label")
ax.set_ylabel("Actual label")
st.pyplot(fig)
plt.close(fig)

st.subheader("Classification Report")
report = classification_report(
    y_test,
    selected_predictions,
    labels=[0, 1],
    target_names=["Benign", "Malignant"],
    zero_division=0,
)
st.text(report)

# ----------------------------------------------------------
# 7. COMPARISON TABLE: ALL MODELS, SAME UPLOADED TEST DATA
# ----------------------------------------------------------
st.subheader("Comparison of All Five Models")
comparison_df = pd.DataFrame(results)
st.dataframe(comparison_df.round(4), hide_index=True)
st.download_button(
    label="Download comparison results (CSV)",
    data=comparison_df.to_csv(index=False),
    file_name="uploaded_test_model_comparison.csv",
    mime="text/csv",
)
st.caption("All results above are computed on the uploaded test data using saved models. No model is retrained here.")
